        public static string T(string es)
        {
            if (es == null) return null;
            if (IsEnglish && En.TryGetValue(es, out var t)) return t;
            return es;
        }

        public static string DisplayName => Current == "en" ? "English" : "Español";

        public static void Set(string code)
        {
            Current = code == "en" ? "en" : "es";
            try { File.WriteAllText(FilePath, "{\"lang\":\"" + Current + "\"}"); } catch { }
        }

        static Lang()
        {
            try
            {
                var j = File.ReadAllText(FilePath);
                using var d = JsonDocument.Parse(j);
                if (d.RootElement.TryGetProperty("lang", out var p) && p.GetString() == "en")
                    Current = "en";
            }
            catch { }
        }
    }
